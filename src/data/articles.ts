export function getArticle(slug: string): WikiArticle | undefined {
  return articles.find((a) => a.slug === slug)
}

// 抜粋表示用に [[slug|表示テキスト]] 記法を平文へ戻す
export function stripMarkup(text: string): string {
  return text.replace(/\[\[([^\]|]+)\|([^\]]+)\]\]/g, '$2').replace(/\[\[([^\]]+)\]\]/g, '$1')
}

export function getByCategory(cat: Category): WikiArticle[] {
  return articles.filter((a) => a.category === cat)
}

export function searchArticles(query: string): WikiArticle[] {
  const q = query.trim().toLowerCase()
  if (!q) return []
  return articles.filter((a) => {
    const haystack = [
      a.title,
      a.reading ?? '',
      a.category,
      ...a.lead,
      ...a.sections.flatMap((s) => [s.heading, ...s.paras]),
    ]
      .join('\n')
      .toLowerCase()
    return q.split(/\s+/).every((term) => haystack.includes(term))
  })
}
